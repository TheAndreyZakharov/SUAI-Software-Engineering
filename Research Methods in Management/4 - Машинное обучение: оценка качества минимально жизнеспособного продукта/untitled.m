%% ПЗ-4. Генерация обучающей выборки (45 наблюдений = по 15 на класс)
rng(2025);

% Удобная функция "усечённое нормальное"
tnorm = @(mu,sig,lo,hi,n) random(truncate(makedist('Normal',mu,sig),lo,hi),n,1);

N = 15;  % по классу

% Класс 1 (высокая): много скачиваний, рейтинг высокий, размер умеренный,
%                    покупатели высокий %, отток низкий
X1_hi = tnorm(65,15,45,100,N);     % тыс. скачиваний
X2_hi = tnorm(8.2,1.0,6.0,10.0,N); % рейтинг 1..10
X3_hi = tnorm(22,5,15,30,N);       % размер, МБ
X4_hi = tnorm(7.5,1.0,5.0,10.0,N); % % покупателей 1..10
X5_hi = tnorm(8.5,2.0,5.0,12.0,N); % отток, % 5..30 (низкий)

% Класс 2 (средняя): всё среднее
X1_md = tnorm(45,12,30,70,N);
X2_md = tnorm(6.0,1.2,4.0,8.5,N);
X3_md = tnorm(27,5,20,35,N);
X4_md = tnorm(5.0,1.2,3.0,7.5,N);
X5_md = tnorm(15,3.0,10,20,N);

% Класс 3 (низкая): мало скачиваний, рейтинг низкий, размер большой,
%                   покупатели низкий %, отток высокий
X1_lo = tnorm(25,8,10,40,N);
X2_lo = tnorm(3.0,1.0,1.0,5.5,N);
X3_lo = tnorm(35,3,30,40,N);
X4_lo = tnorm(2.5,1.0,1.0,4.5,N);
X5_lo = tnorm(22,4.0,16,30,N);

% Собираем матрицу
X = [ ...
    X1_hi X2_hi X3_hi X4_hi X5_hi;  % класс 1
    X1_md X2_md X3_md X4_md X5_md;  % класс 2
    X1_lo X2_lo X3_lo X4_lo X5_lo]; % класс 3

Ynum = [ones(N,1); 2*ones(N,1); 3*ones(N,1)];           % 1/2/3
Y    = categorical(Ynum,[1 2 3],{'1','2','3'});         % категориально

% В таблицу с нужными именами столбцов
mvpData = array2table(X, 'VariableNames',{'X1','X2','X3','X4','X5'});
mvpData.Y = Y;  % отклик — категориальный столбец

% Быстрый скаттер X1–X2 (как в методичке)
figure('Color','w'); hold on;
gscatter(mvpData.X1, mvpData.X2, mvpData.Y, 'rgb', 'o^s', 8, 'on');
xlabel('X1: скачивания (тыс.)'); ylabel('X2: рейтинг (1..10)');
title('Исходные данные (X1–X2)');
grid on; box on;
saveas(gcf,'scatter_X1_X2.png'); close;

% (опционально) сохранить CSV для архива
writetable(mvpData,'mvp_data.csv');
disp('Готово: в Workspace есть таблица mvpData (X1..X5,Y).');