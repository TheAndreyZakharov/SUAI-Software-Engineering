import numpy as np
import scipy.stats as stats

# Данные из таблицы
X = np.array([0.7, 1.6, 1.7, 3.1, 3.9, 4.8, 3.2, 2.7, 1.7, 0.8])
Y = np.array([0.4, 1.3, 2.3, 3.8, 6.9, 7.8, 7.1, 1.9, 1.3, 0.1])

# 1. Оценки математических ожиданий
mean_X = np.mean(X)
mean_Y = np.mean(Y)

# 2. Проверка гипотезы о равенстве математических ожиданий
alpha = 0.05  # Уровень значимости

# Выбираем конкурирующую гипотезу (вариант 77 - нечетный, значит X < Y)
t_stat, p_value = stats.ttest_ind(X, Y, alternative='less')

# Вывод результатов
print("1. Оценка математического ожидания X:", mean_X)
print("2. Оценка математического ожидания Y:", mean_Y)
print("3. Проверка гипотезы H0: M(X) = M(Y) против H1: M(X) < M(Y)")
print("   - t-статистика:", t_stat)
print("   - p-значение:", p_value)
print("   - Гипотеза H0", "отвергается" if p_value < alpha else "принимается")
